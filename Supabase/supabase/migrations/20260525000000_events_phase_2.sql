create table if not exists public.fan_event_images (
  id            bigint generated by default as identity primary key,
  fan_event_id  bigint not null references public.fan_events(id) on delete cascade,
  image_url     text not null,
  storage_path  text not null,
  sort_order    integer not null default 0,
  created_at    timestamptz not null default now()
);

create index if not exists fan_event_images_event_id_idx
  on public.fan_event_images (fan_event_id);

create index if not exists fan_event_images_event_sort_idx
  on public.fan_event_images (fan_event_id, sort_order);

create unique index if not exists fan_event_images_event_sort_unique_idx
  on public.fan_event_images (fan_event_id, sort_order);

alter table public.fan_event_images enable row level security;


drop policy if exists "fan_event_images public read" on public.fan_event_images;
create policy "fan_event_images public read"
  on public.fan_event_images
  for select
  to anon, authenticated
  using (
    exists (
      select 1
      from public.fan_events
      where fan_events.id = fan_event_images.fan_event_id
        and fan_events.is_public = true
    )
  );

drop policy if exists "fan_event_images organizer insert" on public.fan_event_images;
create policy "fan_event_images organizer insert"
  on public.fan_event_images
  for insert
  to authenticated
  with check (
    exists (
      select 1
      from public.fan_events
      where fan_events.id = fan_event_images.fan_event_id
        and fan_events.organizer_profile_id = auth.uid()
    )
  );

drop policy if exists "fan_event_images organizer update" on public.fan_event_images;
create policy "fan_event_images organizer update"
  on public.fan_event_images
  for update
  to authenticated
  using (
    exists (
      select 1
      from public.fan_events
      where fan_events.id = fan_event_images.fan_event_id
        and fan_events.organizer_profile_id = auth.uid()
    )
  )
  with check (
    exists (
      select 1
      from public.fan_events
      where fan_events.id = fan_event_images.fan_event_id
        and fan_events.organizer_profile_id = auth.uid()
    )
  );

drop policy if exists "fan_event_images organizer delete" on public.fan_event_images;
create policy "fan_event_images organizer delete"
  on public.fan_event_images
