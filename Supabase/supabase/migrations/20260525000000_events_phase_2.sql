drop policy if exists "Anyone can view event images"               on storage.objects;
create policy "Anyone can view event images"
  on storage.objects
  for select
  to public
  using (bucket_id = 'event-images'::text);

drop policy if exists "Users can upload their own event images"    on storage.objects;
create policy "Users can upload their own event images"
  on storage.objects
  for insert
  to authenticated
  with check (
    bucket_id = 'event-images'::text
    and (storage.foldername(name))[1] = (auth.uid())::text
  );

drop policy if exists "Users can update their own event images"    on storage.objects;
